/**
 * Reads the real theme palettes (CSS custom properties) from app/globals.css and styles/*.css
 * and writes lib/themePalettes.generated.ts, so theme preview cards always match the actual themes.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const files = [path.join(root, "app/globals.css"), ...fs.readdirSync(path.join(root, "styles")).filter((f) => f.endsWith(".css")).map((f) => path.join(root, "styles", f))];
const css = files.map((f) => fs.readFileSync(f, "utf8")).join("\n");

const THEMES = ["web", "default", "midnight", "ember", "boreal", "xuiClassic", "starWars", "vision", "helloKitty", "barbie"];
const VARS = ["bg", "bg-elevated", "surface-strong", "border", "border-strong", "fg", "fg-muted", "accent", "accent-ambient"];

function block(selectorRe) {
  const m = css.match(selectorRe);
  if (!m) return "";
  const start = m.index + m[0].length;
  const end = css.indexOf("}", start);
  return css.slice(start, end);
}

function readVars(body) {
  const out = {};
  for (const v of VARS) {
    const m = body.match(new RegExp(`(?:^|[;\\s{])--${v}:\\s*([^;]+);`));
    if (m) out[v] = m[1].trim();
  }
  return out;
}

const base = readVars(block(/(?:^|\n):root,\s*\n:root\[data-theme="dark"\]\s*\{/));
const palettes = {};
for (const id of THEMES) {
  const own = id === "default" ? {} : readVars(block(new RegExp(`:root\\[data-panel-theme="${id}"\\]\\s*\\{`)));
  const merged = { ...base, ...own };
  // preview cards need plain colors; fall back to the base value when a theme uses a gradient/var()
  for (const k of VARS) {
    if (!merged[k] || /gradient|var\(/.test(merged[k])) merged[k] = base[k] ?? "#888";
  }
  palettes[id] = merged;
}

const out = `// AUTO-GENERATED by scripts/gen-theme-palettes.mjs — do not edit.
export type ThemePalette = Record<"bg" | "bg-elevated" | "surface-strong" | "border" | "border-strong" | "fg" | "fg-muted" | "accent" | "accent-ambient", string>;

export const THEME_PALETTES: Record<string, ThemePalette> = ${JSON.stringify(palettes, null, 2)};
`;
fs.writeFileSync(path.join(root, "lib/themePalettes.generated.ts"), out);
console.log("wrote lib/themePalettes.generated.ts for", Object.keys(palettes).length, "themes");
